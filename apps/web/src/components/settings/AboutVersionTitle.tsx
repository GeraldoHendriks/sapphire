import { msg, T, useGT } from "gt-react";

import { SAPPHIRE_VERSION, UPSTREAM_VERSION } from "../../sapphire/version";
import { useCopyToClipboard } from "../../hooks/useCopyToClipboard";
import { InlineButton } from "../ui/button";
import { stackedThreadToast, toastManager } from "../ui/toast";
import { Tooltip, TooltipPopup, TooltipTrigger } from "../ui/tooltip";

export function AboutVersionTitle() {
  const gt = useGT();
  const { copyToClipboard } = useCopyToClipboard<void>({
    target: {
      target: "version",
      unavailableMessage: msg("Clipboard API is unavailable while copying version."),
      failureMessage: msg("Failed to copy version to the clipboard."),
    },
    onError: (error) => {
      toastManager.add(
        stackedThreadToast({
          type: "error",
          title: gt("Could not copy version"),
          description: error.message,
        }),
      );
    },
  });

  // Sapphire shows its own version; the T3 Code release it is based on goes along when copied.
  const versionLabel = gt("{version} (T3 Code {upstream})", {
    version: SAPPHIRE_VERSION,
    upstream: UPSTREAM_VERSION,
  });
  return (
    <span className="inline-flex items-baseline gap-2">
      <span>
        <T>Version</T>
      </span>
      <code className="text-2xs font-medium">
        <Tooltip>
          <TooltipTrigger
            render={
              <InlineButton
                tone="muted"
                aria-label={gt("Copy version {version}", { version: versionLabel })}
                onClick={() => copyToClipboard(versionLabel, undefined)}
              >
                {versionLabel}
              </InlineButton>
            }
          />
          <TooltipPopup>
            <T>Copy version</T>
          </TooltipPopup>
        </Tooltip>
      </code>
    </span>
  );
}
